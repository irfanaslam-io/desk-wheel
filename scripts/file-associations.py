#!/usr/bin/env python3
"""
Writes Desk Wheel's file associations for every platform from one list (src/Wheel.Core/Files/FileTypes.json):

    python3 scripts/file-associations.py            # rewrite the generated files
    python3 scripts/file-associations.py --check    # fail if they're out of date (CI)

  * platform/windows/file-types.iss  - the installer's registry entries ("Open with", Default apps)
  * platform/windows/msix/AppxManifest.xml  - the Store package's associations (between the marker comments)
  * platform/mac/DocumentTypes.plist  - CFBundleDocumentTypes and UTImportedTypeDeclarations for Info.plist

Nothing here makes Desk Wheel the default by itself: Windows and macOS list it as an option, and people
choose it (Desk Wheel's Default apps screen helps them do that).
"""
import json
import os
import sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TYPES = json.load(open(os.path.join(ROOT, "src", "Wheel.Core", "Files", "FileTypes.json")))
MANIFEST = os.path.join(ROOT, "platform", "windows", "msix", "AppxManifest.xml")
BEGIN, END = "<!-- file types: begin (scripts/file-associations.py) -->", "<!-- file types: end -->"


def iss():
    out = [
        "; Generated by scripts/file-associations.py from src/Wheel.Core/Files/FileTypes.json. Don't edit by hand.",
        "; \"Open with > Desk Wheel\" for every type it opens, and Desk Wheel listed under Settings > Apps > Default apps.",
        "; Nothing is taken over: people choose Desk Wheel there (its Default apps screen opens that page).",
        'Root: HKCU; Subkey: "Software\\DeskWheel\\Capabilities"; ValueType: string; ValueName: "ApplicationName"; ValueData: "Desk Wheel"; Flags: uninsdeletekey',
        'Root: HKCU; Subkey: "Software\\DeskWheel\\Capabilities"; ValueType: string; ValueName: "ApplicationDescription"; '
        'ValueData: "Picture viewer, media player, PDF viewer and archive opener, with offline file tools."',
        'Root: HKCU; Subkey: "Software\\RegisteredApplications"; ValueType: string; ValueName: "Desk Wheel"; ValueData: "Software\\DeskWheel\\Capabilities"; Flags: uninsdeletevalue',
        'Root: HKCU; Subkey: "Software\\Classes\\Applications\\DeskWheel.exe"; ValueType: string; ValueName: "FriendlyAppName"; ValueData: "Desk Wheel"; Flags: uninsdeletekey',
        'Root: HKCU; Subkey: "Software\\Classes\\Applications\\DeskWheel.exe\\shell\\open\\command"; ValueType: string; ValueData: """{app}\\DeskWheel.exe"" --open ""%1"""',
    ]
    for g in TYPES["groups"]:
        p = g["progId"]
        out += [
            "",
            f"; {g['name']}: open in {g['opensIn']}",
            f'Root: HKCU; Subkey: "Software\\Classes\\{p}"; ValueType: string; ValueData: "{g["friendly"]}"; Flags: uninsdeletekey',
            f'Root: HKCU; Subkey: "Software\\Classes\\{p}"; ValueType: string; ValueName: "FriendlyTypeName"; ValueData: "{g["friendly"]}"',
            f'Root: HKCU; Subkey: "Software\\Classes\\{p}\\DefaultIcon"; ValueType: string; ValueData: """{{app}}\\DeskWheel.exe"",0"',
            f'Root: HKCU; Subkey: "Software\\Classes\\{p}\\shell\\open"; ValueType: string; ValueName: "FriendlyAppName"; ValueData: "Desk Wheel"',
            f'Root: HKCU; Subkey: "Software\\Classes\\{p}\\shell\\open\\command"; ValueType: string; ValueData: """{{app}}\\DeskWheel.exe"" --open ""%1"""',
        ]
        for ext in g["extensions"]:
            out += [
                f'Root: HKCU; Subkey: "Software\\Classes\\{ext}\\OpenWithProgids"; ValueType: string; ValueName: "{p}"; ValueData: ""; Flags: uninsdeletevalue',
                f'Root: HKCU; Subkey: "Software\\DeskWheel\\Capabilities\\FileAssociations"; ValueType: string; ValueName: "{ext}"; ValueData: "{p}"',
                f'Root: HKCU; Subkey: "Software\\Classes\\Applications\\DeskWheel.exe\\SupportedTypes"; ValueType: string; ValueName: "{ext}"; ValueData: ""',
            ]
    return "\n".join(out) + "\n"


def msix(current):
    lines = [BEGIN]
    for g in TYPES["groups"]:
        lines += [
            '        <uap:Extension Category="windows.fileTypeAssociation">',
            f'          <uap3:FileTypeAssociation Name="{g["id"]}" Parameters="--open &quot;%1&quot;">',
            f'            <uap:DisplayName>{escape(g["friendly"])}</uap:DisplayName>',
            "            <uap:SupportedFileTypes>",
            *[f"              <uap:FileType>{ext}</uap:FileType>" for ext in g["extensions"]],
            "            </uap:SupportedFileTypes>",
            "          </uap3:FileTypeAssociation>",
            "        </uap:Extension>",
        ]
    lines.append("        " + END)
    start, end = current.index(BEGIN), current.index(END) + len(END)
    return current[:start] + "\n".join(lines) + current[end:]


def plist():
    def arr(values, indent):
        pad = " " * indent
        return "\n".join(f"{pad}<string>{escape(v)}</string>" for v in values)
    out = ["<!-- Generated by scripts/file-associations.py from src/Wheel.Core/Files/FileTypes.json. -->",
           "<key>CFBundleDocumentTypes</key>", "<array>"]
    for g in TYPES["groups"]:
        # Viewer, ranked Alternate: listed in Open With, never the default unless the person chooses it.
        out += ["  <dict>",
                f"    <key>CFBundleTypeName</key><string>{escape(g['friendly'])}</string>",
                "    <key>CFBundleTypeRole</key><string>Viewer</string>",
                "    <key>LSHandlerRank</key><string>Alternate</string>",
                "    <key>LSItemContentTypes</key>", "    <array>", arr(g["macDocument"], 6), "    </array>",
                "  </dict>"]
    out += ["</array>", "<key>UTImportedTypeDeclarations</key>", "<array>"]
    for t in TYPES["macImport"]:
        out += ["  <dict>",
                f"    <key>UTTypeIdentifier</key><string>{t['uti']}</string>",
                f"    <key>UTTypeDescription</key><string>{escape(t['description'])}</string>",
                "    <key>UTTypeConformsTo</key>", "    <array>", arr(t["conformsTo"], 6), "    </array>",
                "    <key>UTTypeTagSpecification</key>", "    <dict>",
                "      <key>public.filename-extension</key>", "      <array>", arr(t["extensions"], 8), "      </array>",
                f"      <key>public.mime-type</key><string>{t['mime']}</string>",
                "    </dict>",
                "  </dict>"]
    out.append("</array>")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv
    outputs = {
        os.path.join(ROOT, "platform", "windows", "file-types.iss"): iss(),
        MANIFEST: msix(open(MANIFEST).read()),
        os.path.join(ROOT, "platform", "mac", "DocumentTypes.plist"): plist(),
    }
    stale = []
    for path, text in outputs.items():
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                open(path, "w").write(text)
    if check and stale:
        sys.exit("Out of date (run python3 scripts/file-associations.py): " + ", ".join(stale))
    print("Up to date." if not stale else "Wrote: " + ", ".join(stale))


if __name__ == "__main__":
    main()
