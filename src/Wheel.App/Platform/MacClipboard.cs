using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Runtime.InteropServices;
using Wheel.Core.Clipboard;

namespace Wheel.App.Platform;

/// <summary>macOS clipboard (NSPasteboard) for clipboard history and copying files, through the Objective-C runtime.</summary>
internal sealed partial class MacPlatform
{
    [DllImport(ObjC)] private static extern IntPtr objc_autoreleasePoolPush();
    [DllImport(ObjC)] private static extern void objc_autoreleasePoolPop(IntPtr pool);
    [DllImport(ObjC, EntryPoint = "objc_msgSend")] private static extern IntPtr SendPtr(IntPtr receiver, IntPtr selector, IntPtr arg);
    [DllImport(ObjC, EntryPoint = "objc_msgSend")] private static extern IntPtr SendIndex(IntPtr receiver, IntPtr selector, nuint index);
    [DllImport(ObjC, EntryPoint = "objc_msgSend")] private static extern IntPtr SendUIntPtr(IntPtr receiver, IntPtr selector, nuint value, IntPtr arg);
    [DllImport(ObjC, EntryPoint = "objc_msgSend")] private static extern nint SendNInt(IntPtr receiver, IntPtr selector);
    [DllImport(ObjC, EntryPoint = "objc_msgSend")] [return: MarshalAs(UnmanagedType.I1)]
    private static extern bool SendPtrBool(IntPtr receiver, IntPtr selector, IntPtr arg);
    [DllImport(ObjC, EntryPoint = "objc_msgSend")]
    private static extern IntPtr SendUtf8(IntPtr receiver, IntPtr selector, [MarshalAs(UnmanagedType.LPUTF8Str)] string value);

    /// <summary>
    /// Pasteboard markers that password managers and other apps set on things that shouldn't be remembered
    /// (see nspasteboard.org). Anything carrying one is never added to the history.
    /// </summary>
    private static readonly HashSet<string> ConcealedTypes = new(StringComparer.Ordinal)
    {
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "net.antelle.keeweb",
    };

    private static IntPtr Sel(string name) => sel_registerName(name);
    private static IntPtr NSStr(string s) => SendUtf8(objc_getClass("NSString"), Sel("stringWithUTF8String:"), s);
    private static string? FromNSString(IntPtr ns) => ns == IntPtr.Zero ? null : Marshal.PtrToStringUTF8(Send(ns, Sel("UTF8String")));
    private static IntPtr Pasteboard() => Send(objc_getClass("NSPasteboard"), Sel("generalPasteboard"));

    private static byte[]? FromNSData(IntPtr data)
    {
        if (data == IntPtr.Zero) return null;
        var length = (long)SendUInt(data, Sel("length"));
        if (length <= 0 || length > ClipboardStore.MaxImageBytes) return null;
        var bytes = new byte[length];
        Marshal.Copy(Send(data, Sel("bytes")), bytes, 0, (int)length);
        return bytes;
    }

    private static IEnumerable<IntPtr> Items(IntPtr nsArray)
    {
        if (nsArray == IntPtr.Zero) yield break;
        var count = SendUInt(nsArray, Sel("count"));
        for (nuint i = 0; i < count; i++)
            yield return SendIndex(nsArray, Sel("objectAtIndex:"), i);
    }

    public long ClipboardChangeCount()
    {
        var pool = objc_autoreleasePoolPush();
        try { return SendNInt(Pasteboard(), Sel("changeCount")); }
        finally { objc_autoreleasePoolPop(pool); }
    }

    public ClipboardContent? ReadClipboard()
    {
        var pool = objc_autoreleasePoolPush();
        try
        {
            var pb = Pasteboard();
            var types = Items(Send(pb, Sel("types"))).Select(FromNSString).Where(t => t is not null).Select(t => t!).ToList();
            if (types.Count == 0 || types.Any(ConcealedTypes.Contains))
                return null;

            // Files copied in Finder (one pasteboard item each).
            if (types.Contains("public.file-url"))
            {
                var files = new List<string>();
                foreach (var item in Items(Send(pb, Sel("pasteboardItems"))))
                {
                    var text = SendPtr(item, Sel("stringForType:"), NSStr("public.file-url"));
                    if (text == IntPtr.Zero) continue;
                    // Finder may give file-reference URLs (file:///.file/id=…); filePathURL turns them into paths.
                    var url = SendPtr(objc_getClass("NSURL"), Sel("URLWithString:"), text);
                    var path = url == IntPtr.Zero ? IntPtr.Zero : Send(Send(url, Sel("filePathURL")), Sel("path"));
                    if (FromNSString(path) is { Length: > 0 } p) files.Add(p);
                }
                if (files.Count > 0)
                    return new ClipboardContent(null, null, files.ToArray());
            }

            // Images: PNG if offered, else TIFF (what most Mac apps put there) converted to PNG.
            var png = FromNSData(SendPtr(pb, Sel("dataForType:"), NSStr("public.png")));
            if (png is null && types.Contains("public.tiff"))
            {
                var tiff = SendPtr(pb, Sel("dataForType:"), NSStr("public.tiff"));
                var rep = tiff == IntPtr.Zero ? IntPtr.Zero : SendPtr(objc_getClass("NSBitmapImageRep"), Sel("imageRepWithData:"), tiff);
                if (rep != IntPtr.Zero)
                {
                    var noProperties = Send(objc_getClass("NSDictionary"), Sel("dictionary"));
                    png = FromNSData(SendUIntPtr(rep, Sel("representationUsingType:properties:"), 4 /* PNG */, noProperties));
                }
            }
            if (png is not null && Wheel.Core.Clipboard.PngInfo.Size(png) is { } size)
                return new ClipboardContent(null, png, null, size.Width, size.Height);

            var str = FromNSString(SendPtr(pb, Sel("stringForType:"), NSStr("public.utf8-plain-text")));
            return string.IsNullOrEmpty(str) ? null : new ClipboardContent(str, null, null);
        }
        finally
        {
            objc_autoreleasePoolPop(pool);
        }
    }

    /// <summary>Puts files on the clipboard the way Finder's Copy does: paste them into Finder, Mail, Slack…</summary>
    public void CopyFiles(IReadOnlyList<string> paths)
    {
        var pool = objc_autoreleasePoolPush();
        try
        {
            var array = Send(objc_getClass("NSMutableArray"), Sel("array"));
            foreach (var path in paths)
                SendPtr(array, Sel("addObject:"), SendPtr(objc_getClass("NSURL"), Sel("fileURLWithPath:"), NSStr(Path.GetFullPath(path))));
            var pb = Pasteboard();
            Send(pb, Sel("clearContents"));
            if (!SendPtrBool(pb, Sel("writeObjects:"), array))
                throw new IOException("macOS didn't accept the files on the clipboard.");
        }
        finally
        {
            objc_autoreleasePoolPop(pool);
        }
    }
}
